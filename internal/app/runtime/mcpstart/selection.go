package mcpstart

import (
	"sort"
	"strings"
)

// NormalizeSelection trims, deduplicates and sorts an MCP selection.
func NormalizeSelection(names []string) []string {
	seen := make(map[string]bool, len(names))
	out := make([]string, 0, len(names))
	for _, raw := range names {
		name := strings.TrimSpace(raw)
		if name == "" || seen[name] {
			continue
		}
		seen[name] = true
		out = append(out, name)
	}
	sort.Strings(out)
	return out
}
